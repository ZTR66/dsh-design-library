import { buildIndex } from './lib/scan.js';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
const root = join(process.cwd(), 'data');
const idx = await buildIndex([root], { seedRoot: root });
const by = {};
for (const e of idx.entries) by[e.kind] = (by[e.kind] ?? 0) + 1;
const lib = JSON.parse(await readFile(join(root,'video-styles','shots','library.json'),'utf8'));
console.log('scan total', idx.total, JSON.stringify(by));
console.log('shot cards in library.json:', lib.cards.length);
console.log('sum =', idx.total + lib.cards.length);
const cats = {};
for (const c of lib.cards) cats[c.category] = (cats[c.category]??0)+1;
console.log('shot categories:', JSON.stringify(cats));
